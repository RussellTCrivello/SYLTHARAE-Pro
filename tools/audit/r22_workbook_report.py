"""Generate ``audit_report/r22_workbook/REPORT.md`` from measurement.

Every number in the report is read here - from the workbook through the rules
engine, and from the database when one is named - so nothing is transcribed by
hand and a stale figure cannot survive a run.

Usage::

    python3 tools/audit/r22_workbook_report.py                     # workbook only
    python3 tools/audit/r22_workbook_report.py --database taxonomy_dev
    python3 tools/audit/r22_workbook_report.py --out report.md

With a database the report additionally states what the database holds and
whether a second sync would change anything (the idempotency claim).
"""

from __future__ import annotations

import argparse
import datetime
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

WORKBOOK = ROOT / "classification" / "domain_data.xlsx"
DEFAULT_OUT = ROOT / "audit_report" / "r22_workbook" / "REPORT.md"


def _sha256(path: Path) -> str:
    import hashlib

    return hashlib.sha256(path.read_bytes()).hexdigest()


def workbook_facts() -> dict:
    from apps.importing.validators import workbook_rules as rules

    workbook = rules.read(str(WORKBOOK))
    return {
        "layout": workbook.layout,
        "categories": len(workbook.categories),
        "terms": workbook.total_terms(),
        "distinct_terms": workbook.distinct_terms(),
        "keywords": workbook.total_keywords(),
        "distinct_keywords": workbook.distinct_keywords(),
        "shared_phrases": len(workbook.shared_keywords()),
        "decisions": len(workbook.decisions),
        "errors": len(workbook.errors),
        "owner_rows": len(workbook.owners),
        "sha256": _sha256(WORKBOOK),
        "errors_detail": [str(v) for v in workbook.errors],
    }


def database_facts(database: str) -> dict:
    import json

    import psycopg2

    from tools.i18n import sync_taxonomy as sync

    cfg = {
        "host": os.environ.get("DB_HOST", "localhost"),
        "port": int(os.environ.get("DB_PORT", "5432")),
        "user": os.environ.get("DB_USER", "postgres"),
        "password": os.environ.get("DB_PASSWORD", ""),
        "database": database,
    }
    conn = psycopg2.connect(**cfg)
    try:
        conn.autocommit = True
        counts = {}
        for table in ("words", "categorys", "keywords", "words_categorys"):
            with conn.cursor() as cur:
                cur.execute(f"SELECT count(*) FROM {table}")  # nosec B608 - fixed names
                counts[table] = cur.fetchone()[0]

        from apps.importing.validators import workbook_rules as rules

        workbook = rules.read(str(WORKBOOK))
        plan = sync.build_plan(conn, workbook)
        planned = {
            "categories to create": len(plan.create_categories),
            "categories to rename": len(plan.rename_categories),
            "categories in the database only": len(plan.missing_categories),
            "words to create": len(plan.create_words),
            "terms to link": len(plan.link_terms),
            "terms to unlink": len(plan.unlink_terms),
            "keywords to create": len(plan.create_keywords),
            "keywords to delete": len(plan.delete_keywords),
        }
        return {"counts": counts, "plan": planned,
                "idempotent": plan.changes == 0}
    finally:
        conn.close()


def _table(rows, header) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def render(facts: dict, db: dict | None, command: str) -> str:
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# Report 22: the category workbook as the source of truth",
        "",
        f"Generated by `{command}` on {stamp}. Every figure below is read from the",
        "workbook (through the rules engine) and from the database named on the",
        "command line. Nothing here is transcribed by hand.",
        "",
        "## The workbook",
        "",
        _table([
            ("layout", facts["layout"]),
            ("categories (worksheets)", facts["categories"]),
            ("term rows", facts["terms"]),
            ("distinct terms", facts["distinct_terms"]),
            ("keyword rows", facts["keywords"]),
            ("distinct phrases", facts["distinct_keywords"]),
            ("phrases listed in more than one worksheet", facts["shared_phrases"]),
            ("ownership decisions reported", facts["decisions"]),
            ("rows in `_Keyword Owners`", facts["owner_rows"]),
            ("rule violations", facts["errors"]),
            ("sha256", facts["sha256"]),
        ], ("measurement", "value")),
        "",
        "A rule violation refuses the import and is named by sheet and cell:",
        "",
        "```",
        "\n".join(facts["errors_detail"]) if facts["errors_detail"] else "none",
        "```",
        "",
        "## Rules enforced",
        "",
        _table([
            ("1", "the worksheet name is the category name", "`apps/importing/validators/workbook_rules.py`"),
            ("2", "the worksheet's rows are its `Term` and `Keyword` columns", "same module"),
            ("3", "a term is exactly one word", "same module, `TERM_HAS_WHITESPACE`"),
            ("4", "a keyword is two or more words", "same module, `KEYWORD_SINGLE_WORD`"),
        ], ("#", "rule", "where"),
        ),
        "",
        "The same module decides for the importer, the sync tool and the test",
        "suite, so the three cannot disagree.",
        "",
    ]

    if db is None:
        lines += [
            "## The database",
            "",
            "Not measured: no `--database` was given, so this report says nothing",
            "about the stored state. Run with",
            "`DB_HOST=... DB_NAME=... python3 tools/audit/r22_workbook_report.py --database <name>`",
            "to include it.",
            "",
        ]
    else:
        lines += [
            "## The database",
            "",
            _table([(table, count) for table, count in db["counts"].items()],
                   ("table", "rows")),
            "",
            "A sync plan computed against those rows now:",
            "",
            _table([(key, value) for key, value in db["plan"].items()],
                   ("planned change", "count")),
            "",
            "**Idempotent:** " + ("yes - a second sync writes nothing."
                                  if db["idempotent"] else
                                  "**no** - the plan above is not empty."),
            "",
        ]

    lines += [
        "## Reproducing",
        "",
        "```bash",
        "python3 tools/i18n/sync_taxonomy.py --check      # rules and ownership decisions",
        "python3 tools/i18n/sync_taxonomy.py              # planned changes, writes nothing",
        "python3 tools/i18n/sync_taxonomy.py --apply      # reconcile, one transaction",
        "python3 -m pytest tests/unit/test_workbook_rules.py \\",
        "                 tests/unit/test_committed_workbook.py \\",
        "                 tests/unit/test_workbook_loader.py \\",
        "                 tests/unit/test_word_repository.py \\",
        "                 tests/unit/test_keyword_repository.py -q",
        "python3 -m pytest tests/integration/test_sync_taxonomy.py -q   # needs PostgreSQL",
        "```",
        "",
        "The operator's contract is [docs/DATA_ENTRY.md](../../docs/DATA_ENTRY.md).",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--database", help="a database to measure as well")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    facts = workbook_facts()
    db = database_facts(args.database) if args.database else None
    command = "python3 tools/audit/r22_workbook_report.py" + (
        f" --database {args.database}" if args.database else "")
    text = render(facts, db, command)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")
    print(f"  categories {facts['categories']}, terms {facts['terms']}, "
          f"keywords {facts['keywords']}, violations {facts['errors']}")
    if db is not None:
        print(f"  database rows {db['counts']}, idempotent {db['idempotent']}")
    return 0 if facts["errors"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
