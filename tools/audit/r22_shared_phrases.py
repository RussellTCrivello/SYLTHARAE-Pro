#!/usr/bin/env python3
"""Count what the schema cannot store, from the committed workbook.

``keywords.keyword`` is UNIQUE, and its value is the list of word ids in the
phrase. So a phrase listed in two worksheets can be stored in one of them, and
the other listing becomes a *membership that is not stored* - a lost decision,
not a lost bug. This tool counts them, names the categories that lose them, and
says whether ``_Keyword Owners`` decided each one or a default did.

Read-only: it reads the workbook through the same rules the sync uses and writes
a markdown table. No database is opened, because the question is about the
workbook - the database can only hold one copy by construction.

Usage::

    python3 tools/audit/r22_shared_phrases.py --out audit_report/r22_workbook/SHARED_PHRASES.md
"""

from __future__ import annotations

import argparse
import collections
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from apps.importing.validators import workbook_rules as rules  # noqa: E402


def analyse(path: pathlib.Path, renames=None) -> dict:
    workbook = rules.read(str(path), renames=renames or {})
    shared = workbook.shared_keywords()
    decided = {phrase for phrase in shared if workbook.owner_of(phrase) in
               {c.name for c in workbook.categories}
               and phrase in workbook.owners}
    rows = []
    losers = collections.Counter()
    for phrase in sorted(shared):
        listed_in = sorted(shared[phrase])
        owner = workbook.owner_of(phrase)
        lost = [name for name in listed_in if name != owner]
        for name in lost:
            losers[name] += 1
        rows.append({
            "phrase": phrase,
            "owner": owner,
            "listed_in": listed_in,
            "lost": lost,
            "decided_by": (rules.OWNERS_SHEET if phrase in workbook.owners
                           else "first worksheet in workbook order"),
        })
    return {
        "ok": workbook.ok,
        "errors": [str(violation) for violation in workbook.errors],
        "categories": len(workbook.categories),
        "shared": rows,
        "memberships": sum(len(row["listed_in"]) for row in rows),
        "not_stored": sum(len(row["lost"]) for row in rows),
        "declared": len(decided),
        "losers": losers.most_common(),
    }


def _relative(path: pathlib.Path) -> str:
    try:
        return str(pathlib.Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return pathlib.Path(path).name


def render(result: dict, path: pathlib.Path) -> list:
    out = ["# Shared phrases: what the schema cannot store (D)", "",
           "Generated by `tools/audit/r22_shared_phrases.py` from",
           f"`{_relative(path)}` through `apps.importing.validators.workbook_rules`.", "",
           "## The numbers", "",
           "| measure | value |", "|---|---|",
           f"| category worksheets | {result['categories']} |",
           f"| phrases listed in more than one worksheet | {len(result['shared'])} |",
           f"| memberships those phrases add up to | {result['memberships']} |",
           f"| memberships **not stored** (one phrase per category) | "
           f"{result['not_stored']} |",
           f"| shared phrases named in `{rules.OWNERS_SHEET}` | "
           f"{result['declared']} |",
           f"| shared phrases decided by workbook order (no line in the sheet) | "
           f"{len(result['shared']) - result['declared']} |",
           "",
           "## Which categories lose a membership, and how many", "",
           "| category | memberships it lists but does not own |", "|---|---|"]
    for name, count in result["losers"]:
        out.append(f"| {name} | {count} |")
    if not result["losers"]:
        out.append("| — | 0 |")
    out += ["", "## Every shared phrase", "",
            "| phrase | stored in | also listed in (lost) | decided by |",
            "|---|---|---|---|"]
    for row in result["shared"]:
        out.append("| `{}` | {} | {} | {} |".format(
            row["phrase"], row["owner"],
            ", ".join(row["lost"]) or "—", row["decided_by"]))
    if not result["shared"]:
        out.append("| — | — | — | — |")
    out += ["",
            "## What this means, and the decision it asks for", "",
            "A member that lists a phrase its own category does not own is not a",
            "typo the tool can fix: the schema stores the phrase once, so the",
            "second listing cannot exist. Two honest options, and this round takes",
            "the first:", "",
            f"1. **Report it as a standing fact** (this round). `GET /api/taxonomy/status`",
            f"   returns `not_stored_count` beside `summary`, whose sentence names",
            f"   the count, the reason and `{rules.OWNERS_SHEET}`; the sync result",
            "   carries the same list. Nobody has to read a log to learn it.",
            "   The orphan-row removal path is the same shape: `orphan_words_count`",
            "   and a sentence naming `prune_words` as the confirmation, because a",
            "   drift report that only counts is a report nobody can act on.",
            "2. **Store it anyway** - which needs a schema change: the unique",
            "   constraint is on `keywords.keyword` alone. The DDL is written up in",
            "   `audit_report/r22_workbook/MIGRATION_PROPOSALS.md` (proposal A) and",
            "   **not applied**.", ""]
    if not result["ok"]:
        out += ["The workbook breaks a rule, so the counts above are from a file "
                "the sync would refuse:", ""]
        out += [f"* {message}" for message in result["errors"][:10]]
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--workbook", type=pathlib.Path,
                    default=ROOT / "classification/domain_data.xlsx")
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args(argv)

    result = analyse(args.workbook)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(render(result, args.workbook)), encoding="utf-8")
    print(f"wrote {args.out}: {len(result['shared'])} shared phrases, "
          f"{result['not_stored']} memberships not stored, "
          f"{result['declared']} decided in the owners sheet")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
