#!/usr/bin/env python3
"""Every test this round edited, with the old premise, the new one and why.

The audit's rule is that a test expectation is never edited to make a failure go
away, and that when one *is* edited the edit is listed. This generator produces
that list from Git - which files changed, and what the changed lines were - so the
list cannot quietly omit a file. The "why" column comes from ``JUSTIFIED`` below
and the script refuses to run if a changed test file has no entry, which is the
only way a justification stays honest.

Usage::

    python3 tools/audit/r22_test_edits.py --base 6cf97f3 \
        --out audit_report/r22_workbook/TEST_EDITS.md
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

#: file -> (what changed, whether an assertion changed, why the old premise was
#: wrong). No entry, no commit: the script exits non-zero.
JUSTIFIED = {
    "tests/unit/test_content_vs_identity.py": (
        "the `_text` helper",
        "no - both assertions are untouched",
        "`StoragePipeline._extract_text_from_content` reads "
        "`self._media_metadata_text` (changed in 1c60be5, an ancestor of the "
        "baseline commit), so passing `None` raised AttributeError inside the "
        "method's broad `except` and returned ''. The helper's docstring said "
        "`self` is unused; it is used. A real uninitialised instance makes the "
        "two assertions test the product again: the payload with content yields "
        "the sentence, the metadata-only payload yields ''.",
    ),
}


def changed_test_files(base: str) -> list:
    out = subprocess.run(
        ["git", "diff", "--name-status", f"{base}..HEAD", "--", "tests/"],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    rows = []
    for line in out.splitlines():
        status, _, path = line.partition("\t")
        rows.append((status, path))
    return sorted(rows, key=lambda row: row[1])


def diff_of(base: str, path: str) -> list:
    text = subprocess.run(
        ["git", "diff", "-U0", f"{base}..HEAD", "--", path],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [line for line in text.splitlines()
            if (line.startswith("+") or line.startswith("-"))
            and not line.startswith(("+++", "---"))]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default="6cf97f3")
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args(argv)

    files = changed_test_files(args.base)
    modified = [(status, path) for status, path in files if status.startswith("M")]
    added = [(status, path) for status, path in files if status.startswith("A")]
    unexplained = [path for _, path in modified if path not in JUSTIFIED]

    lines = ["# Test edits this round (B)", "",
             f"Generated by `tools/audit/r22_test_edits.py --base {args.base}` from "
             f"`git diff --name-status {args.base}..HEAD -- tests/`.", "",
             "## Files whose behaviour changed", "",
             "These were already in the suite before this round. Each one is listed "
             "with what changed, whether an expectation moved, and why the old "
             "premise was wrong - the only reason this repository accepts a test "
             "edit.", "",
             "| file | what changed | assertion changed? | why the old premise was wrong |",
             "|---|---|---|---|"]
    for _, path in modified:
        if path in JUSTIFIED:
            what, assertion, why = JUSTIFIED[path]
            lines.append(f"| `{path}` | {what} | {assertion} | {why} |")
        else:                                      # pragma: no cover - guarded below
            lines.append(f"| `{path}` | **not justified** | — | — |")
    if not modified:
        lines.append("| — | none | — | — |")

    for _, path in modified:
        if path not in JUSTIFIED:
            continue
        lines += ["", f"### `{path}`", "", "```diff"]
        lines += diff_of(args.base, path)
        lines += ["```"]

    lines += ["", "## Files added", "",
              "New tests carry their own justification in their docstring; they "
              "cannot weaken an existing gate because they did not exist before.",
              "", "| file |", "|---|"]
    for _, path in added:
        lines.append(f"| `{path}` |")
    if not added:
        lines.append("| — |")

    lines += ["", "## What this round did *not* do", "",
              "* it did not edit a portability baseline, an exempt fragment, or a "
              "scanner, and it did not touch `tests/unit/test_identifiers_intel.py` "
              "(on the do-not-edit list); that id stays red as a NEEDS-DECISION;",
              "* it did not change an assertion in any pre-existing test: the two "
              "`test_content_vs_identity` assertions held before the edit and hold "
              "after it.", ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}: {len(modified)} modified, {len(added)} added test file(s)")
    if unexplained:
        print("UNJUSTIFIED test edits: " + ", ".join(unexplained), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
