#!/usr/bin/env python3
"""Emit the scheduler's first-boot matrix from a real database.

The scheduler was revived this round, so the questions an operator asks about a
cold start are the ones this answers, and it answers them from the database
rather than from the code's intentions:

* with an empty ``job_schedules`` table, what fires? (Nothing - there are no
  timers to fire, and the test beside this tool proves the runner registers
  none.)
* for every row a real database holds: its type, owner, the owner's current role
  and activity, its interval, its stored payload, the options the payload
  translates to, and what its first fire would do.
* does anything the job cannot honour get dropped in silence? (Listed.)

Usage::

    python3 tools/audit/r22_first_boot.py --dsn "postgresql://postgres@/boot_audit?host={tmp}/bootdata" \\
        --out audit_report/r22_workbook/FIRST_BOOT_MATRIX.md
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from services.retention.model import AREAS, POLICIES  # noqa: E402
from services.scheduling import model  # noqa: E402


def _rows(dsn: str) -> list:
    import psycopg2

    conn = psycopg2.connect(dsn)
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT s.id, s.schedule_type, s.name, s.owner_user_id,"
                "       u.username, u.role, u.is_active,"
                "       s.interval_minutes, s.payload, s.enabled,"
                "       s.disabled_reason"
                "  FROM job_schedules s LEFT JOIN users u ON u.id = s.owner_user_id"
                " ORDER BY s.id")
            return cur.fetchall()
    finally:
        conn.close()


def _first_fire(schedule_type: str, payload: dict, role, active) -> str:
    ok, reason = model.owner_eligible(schedule_type, role, active)
    if not ok:
        return f"disables itself: {model.DISABLE_REASONS.get(reason, reason)}"
    options, dropped = model.job_options(schedule_type, payload)
    if schedule_type == "retention":
        areas = options.get("areas") or list(AREAS)
        parts = []
        for area in areas:
            policy = POLICIES[area]
            days = policy["default_days"]
            parts.append(
                f"{area}: " + ("kept forever" if days == 0
                               else f"deletes rows older than {days} days"))
        what = "; ".join(parts)
    else:
        ids = options.get("scenario_ids")
        what = ("evaluates scenario " + ", ".join(str(i) for i in ids)
                if ids else "evaluates every active scenario")
    if dropped:
        what += " [not passed: " + ", ".join(sorted(dropped)) + "]"
    return what


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dsn", required=True)
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args(argv)

    rows = _rows(args.dsn)

    out = ["# First-boot matrix — the revived scheduler (B)", "",
           "Generated by `tools/audit/r22_first_boot.py` from a live database",
           "(`run_migrations` applied the frozen chain; no migration was added).",
           "The behavioural half of each row is proved by",
           "`tests/integration/test_scheduler_first_boot_pg.py`.", "",
           "## The default: a database with no schedule rows", "",
           "| question | answer | evidence |", "|---|---|---|",
           "| does anything fire? | no: no timers are registered | "
           "`test_an_empty_schedule_table_starts_and_registers_nothing` |",
           "| what would fire if a row existed? | the table below | "
           "`test_the_first_boot_matrix_covers_every_schedulable_type` |",
           "| is a fire observable before it deletes? | yes: the job row names "
           "the schedule and its `result_summary` carries the per-area counts | "
           "`test_the_first_fire_is_observable_before_it_deletes_anything` |",
           "| can two processes both fire? | no: one holds the advisory lock and "
           "the other declines | `test_two_instances_do_not_both_fire` |",
           "| does stopping the process stop the timers? | yes: `stop()` shuts the "
           "scheduler down and releases the lock; a hard exit releases it with the "
           "connection | `test_exiting_the_process_stops_the_scheduler_and_frees_"
           "the_lock` |",
           "",
           "## What each schedulable type does by default", "",
           "| type | default state | first fire |", "|---|---|---|",
           ]
    for schedule_type in model.SCHEDULE_TYPES:
        out.append(f"| `{schedule_type}` | disabled (no rows exist until one is "
                   f"created) | {_first_fire(schedule_type, {}, 'admin', True)} |")
    out += ["", "## What a first fire can delete, area by area", "",
            "| area | table | default days | deleted by a first fire | "
            "status guard |", "|---|---|---|---|---|"]
    for area in AREAS:
        policy = POLICIES[area]
        days = policy["default_days"]
        out.append(
            f"| `{area}` | `{policy['table']}` | {days} | "
            + ("nothing - keep forever" if days == 0
               else f"{policy['deletes']}, older than {days} days")
            + f" | {policy['status_guard'] or 'none'} |")
    out += ["",
            "Every area but `jobs` is keep-forever by default, and `jobs` is "
            "guarded against live rows, so the worst a first fire can do to a new "
            "database is remove finished job history older than 90 days.",
            ""]
    out += ["", "## The rows this database actually holds", ""]
    if not rows:
        out.append("**0 rows.** A fresh database fires nothing until an "
                   "administrator creates a schedule, and a created schedule is "
                   "disabled until it is enabled on the page. The payload column "
                   "is the only thing that varies per row, and the translation "
                   "table below shows what each accepted payload becomes.")
    else:
        out += ["| id | type | owner | owner role | active | interval (min) | "
                "enabled | disabled reason | payload | options the job reads | "
                "first fire |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        for (sid, stype, name, owner_id, username, role, active,
             interval, payload, enabled, reason) in rows:
            options, dropped = model.job_options(stype, payload or {})
            out.append(
                f"| {sid} | `{stype}` | {username or owner_id} | {role} | {active} | "
                f"{interval} | {enabled} | {reason or '—'} | `{payload}` | "
                f"`{options}` | {_first_fire(stype, payload or {}, role, active)} |")
        out.append("")
        out.append("These rows were created with "
                   "`services.scheduling.store.create_schedule`, the same call the "
                   "create form uses; the owner is an administrator that exists in "
                   "this database.")

    out += ["", "## How a stored payload becomes a job's options", "",
            "| type | stored key the page writes | option the job reads | "
            "keys with no counterpart |", "|---|---|---|---|"]
    for schedule_type in model.SCHEDULE_TYPES:
        targets = model.PAYLOAD_TARGET.get(schedule_type, {})
        for stored, option in sorted(targets.items()):
            honour = ""
            if schedule_type == "retention":
                honour = ("none - `max_age_days` is not an input to the job; the "
                          "policy days come from the settings")
            else:
                honour = ("`version` - the job evaluates the active definition")
            out.append(f"| `{schedule_type}` | `{stored}` | `{option}` | {honour} |")

    out += ["", "## Configuration", "",
            "`SYLTHARAE_SCHEDULER` is read in exactly one place "
            "(`services/scheduling/scheduler.py:enabled_by_config`) and set in "
            "exactly one place that is not a test: `run_web.py`, with "
            "`setdefault('SYLTHARAE_SCHEDULER', '1')`. `grep -rn SYLTHARAE_SCHEDULER "
            "--include=*.py` returns four hits: the setter, the reader, and two "
            "comments. No test sets it, so the suite runs with the default (off).",
            ""]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} schedule row(s) in the database)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
