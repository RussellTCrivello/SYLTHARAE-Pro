def _apply(lang: str, mapping: dict[str, str]) -> None:
    path = ROOT / "translations" / lang / "LC_MESSAGES" / "messages.po"
    with path.open("rb") as f:
        catalog = read_po(f, locale=lang)
    for msgid in ALL_EXPORT_SURFACE_MSGIDS:
        msg = catalog.get(msgid)
        if msg is None:
            continue
        if lang == "en":
            if not msg.string:
                msg.string = msgid
        else:
            text = mapping.get(msgid)
            if text:
                msg.string = text
            elif not msg.string:
                msg.string = msgid
        msg.flags.discard("fuzzy")
    with path.open("wb") as f:
        write_po(f, catalog, width=88)
    print(f"filled {lang}")


def main() -> None:
    import scripts.fix_file_action_button_translations as fix_btn  # noqa: WPS433

    fix_btn.main()
    _apply("en", {})
    for lang in ("ar", "he", "fa", "hr"):
        _apply(lang, EXTRA[lang])


if __name__ == "__main__":
    main()
