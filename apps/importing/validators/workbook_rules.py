"""The rules a category workbook must satisfy, and the reader that enforces them.

The workbook is the operator's data file: one worksheet per category, and the
worksheet's name *is* the category's name. This module is the single source of
truth for what that file may contain, so the in-app importer
(``apps.importing.data.loader``), the command-line sync
(``tools/i18n/sync_taxonomy.py``) and the tests cannot drift apart.

The four rules
-------------
R1  **Worksheet name = category name.** ``Networks`` is the category
    ``Networks``. There is no separate name cell to disagree with it, and the
    ``Master Index`` sheet is derived (regenerated by the tool), never read.
R2  **A category term is exactly one word.** No spaces, no tabs. A cell with
    two words in the ``Term`` column is an error, not something to split
    silently: splitting hides a typing mistake the operator wanted to make in
    the other column.
R3  **A keyword is two or more words** - a phrase or an expression. One word in
    the ``Keyword`` column is an error for the same reason.
R4  **No duplicates.** A term or a keyword may not repeat inside one worksheet,
    and the same text may not be both.

Why a rule needs a *decision* rather than an error
--------------------------------------------------
``keywords.keyword`` is ``UNIQUE`` **globally** in the schema (see
``database/migrations/m0001_baseline.py``): a phrase belongs to exactly one
category. The operator's file has phrases that genuinely fit several domains
("load balancing" is listed under four). That cannot be stored as written, so it
is reported as a ``decision`` with the owner the sync will use, and the
``_Keyword Owners`` sheet records the choice in a form the operator can edit.
Nothing is dropped silently; see ``docs/reference/DATA_ENTRY.md``.
"""
from __future__ import annotations

import collections
import re
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Optional, Sequence, Tuple

#: Header text of the two data columns. Case-insensitive, whitespace-normalised.
TERM_HEADER = "Term"
KEYWORD_HEADER = "Keyword"

#: A generated table of contents. Derived from the category sheets, never read.
INDEX_SHEET = "Master Index"

#: Documentation sheet, ignored by every reader.
README_SHEET = "_README"

#: Which category owns a phrase that appears in several worksheets.
OWNERS_SHEET = "_Keyword Owners"

#: Sheets whose names start with this are never categories.
IGNORED_PREFIX = "_"

#: Longest single word accepted. Matches ``MAX_REGULAR_WORD_LENGTH`` in
#: ``apps/importing/utils/constants.py``, the limit the reader pipeline uses.
MAX_TERM_CHARS = 100

#: Longest keyword accepted. Well above the longest real phrase measured in the
#: operator's file (52 characters), low enough to catch a pasted paragraph.
MAX_KEYWORD_CHARS = 300

#: Excel's own limit, asserted here so a too-long sheet name is a data error
#: rather than a save failure.
MAX_SHEET_NAME_CHARS = 31

_SEVERITY = {"error": "error", "decision": "decision"}


def normalise(value: object) -> str:
    """Collapse runs of whitespace and strip the ends.

    Excel users paste from browsers and PDFs; ``"  Load\\u00a0balancing "`` and
    ``"Load balancing"`` must be the same keyword, or the uniqueness checks and
    the database's ``UNIQUE`` disagree.
    """
    if value is None:
        return ""
    return " ".join(str(value).replace("\u00a0", " ").split())


def word_count(text: str) -> int:
    return len(text.split())


def is_single_word(text: str) -> bool:
    return word_count(text) == 1


def is_keyword(text: str) -> bool:
    return word_count(text) >= 2


def is_ignored_sheet(name: str) -> bool:
    """True for sheets that are not categories (docs, index, owner table)."""
    clean = normalise(name)
    return (
        clean.startswith(IGNORED_PREFIX)
        or clean.casefold() == INDEX_SHEET.casefold()
        or clean.casefold() == OWNERS_SHEET.casefold()
    )


@dataclass(frozen=True)
class Violation:
    """One finding, in a form the operator can act on without opening a log."""

    code: str
    sheet: str
    cell: str
    value: str
    message: str
    severity: str = "error"

    def __str__(self) -> str:
        where = f"{self.sheet}!{self.cell}" if self.cell else self.sheet
        return f"[{self.severity}] {self.code} {where}: {self.message}"


@dataclass
class Entry:
    """One accepted cell: its text and where it came from."""

    text: str
    row: int
    column: str  # "A" for a term, "B" for a keyword

    @property
    def cell(self) -> str:
        return f"{self.column}{self.row}"


@dataclass
class Category:
    """One worksheet: the category's name, its terms and its keywords."""

    name: str
    terms: List[Entry] = field(default_factory=list)
    keywords: List[Entry] = field(default_factory=list)

    @property
    def term_texts(self) -> List[str]:
        return [entry.text for entry in self.terms]

    @property
    def keyword_texts(self) -> List[str]:
        return [entry.text for entry in self.keywords]

    def __len__(self) -> int:
        return len(self.terms) + len(self.keywords)


@dataclass
class Workbook:
    """Everything a reader needs, plus every rule breach found while reading."""

    path: str
    categories: List[Category] = field(default_factory=list)
    violations: List[Violation] = field(default_factory=list)
    owners: Dict[str, str] = field(default_factory=dict)
    layout: str = "two-column"

    # -- queries ---------------------------------------------------------
    @property
    def errors(self) -> List[Violation]:
        return [v for v in self.violations if v.severity == "error"]

    @property
    def decisions(self) -> List[Violation]:
        return [v for v in self.violations if v.severity == "decision"]

    @property
    def ok(self) -> bool:
        return not self.errors

    def category(self, name: str) -> Optional[Category]:
        folded = normalise(name).casefold()
        for category in self.categories:
            if category.name.casefold() == folded:
                return category
        return None

    # -- derived views ---------------------------------------------------
    def total_terms(self) -> int:
        return sum(len(c.terms) for c in self.categories)

    def total_keywords(self) -> int:
        return sum(len(c.keywords) for c in self.categories)

    def distinct_terms(self) -> int:
        return len({t.casefold() for c in self.categories for t in c.term_texts})

    def distinct_keywords(self) -> int:
        return len({k.casefold() for c in self.categories for k in c.keyword_texts})

    def shared_keywords(self) -> Dict[str, List[str]]:
        """Phrase -> categories that list it, for phrases in more than one."""
        owners: Dict[str, List[str]] = collections.defaultdict(list)
        for category in self.categories:
            for text in category.keyword_texts:
                owners[text.casefold()].append(category.name)
        return {k: v for k, v in owners.items() if len(v) > 1}

    def owner_of(self, phrase: str) -> Optional[str]:
        """The category a shared phrase belongs to under the current rules.

        ``_Keyword Owners`` wins when it names one; otherwise the first
        worksheet that lists the phrase, in workbook order. Deterministic, so a
        second sync of an unchanged file changes nothing.
        """
        chosen = self.owners.get(normalise(phrase).casefold())
        if chosen:
            return chosen
        for category in self.categories:
            if any(text.casefold() == phrase.casefold() for text in category.keyword_texts):
                return category.name
        return None

    def as_dict(self) -> Dict[str, object]:
        """The shape the sync tool writes to its report."""
        return {
            "path": self.path,
            "layout": self.layout,
            "categories": len(self.categories),
            "terms": self.total_terms(),
            "keywords": self.total_keywords(),
            "distinct_terms": self.distinct_terms(),
            "distinct_keywords": self.distinct_keywords(),
            "shared_keywords": len(self.shared_keywords()),
            "errors": len(self.errors),
            "decisions": len(self.decisions),
        }


# ---------------------------------------------------------------------------
# reading
# ---------------------------------------------------------------------------
def _header_text(value: object) -> str:
    return normalise(value).casefold()


def _looks_like_header(row: Sequence[object]) -> bool:
    cells = [_header_text(cell) for cell in list(row)[:2] + [None, None]]
    return cells[0].startswith(TERM_HEADER.casefold()) or \
        cells[1].startswith(KEYWORD_HEADER.casefold())


def _read_category(sheet, workbook: Workbook) -> Optional[Category]:
    """Read one worksheet into a :class:`Category`, recording what is wrong."""
    name = normalise(sheet.title)
    category = Category(name=name)

    rows = list(sheet.iter_rows(values_only=True))
    if not rows:
        workbook.violations.append(Violation(
            "SHEET_EMPTY", name, "", "", "the worksheet has no rows"))
        return category

    layout_two_column = _looks_like_header(rows[0])
    workbook.layout = "two-column" if layout_two_column else "legacy-single-column"

    if layout_two_column:
        header = list(rows[0]) + [None, None]
        if not _header_text(header[0]).startswith(TERM_HEADER.casefold()):
            workbook.violations.append(Violation(
                "MISSING_HEADER", name, "A1", normalise(header[0]),
                f"the first column must be headed {TERM_HEADER!r}"))
        if not _header_text(header[1]).startswith(KEYWORD_HEADER.casefold()):
            workbook.violations.append(Violation(
                "MISSING_HEADER", name, "B1", normalise(header[1]),
                f"the second column must be headed {KEYWORD_HEADER!r}"))
        data_rows = rows[1:]
        offset = 2
    else:
        data_rows = rows
        offset = 1

    seen_terms: Dict[str, Entry] = {}
    seen_keywords: Dict[str, Entry] = {}

    for index, row in enumerate(data_rows):
        excel_row = index + offset
        cells = list(row) + [None, None]

        if layout_two_column:
            slots = (("A", cells[0], "term"), ("B", cells[1], "keyword"))
        else:
            # Legacy layout: one column, and the shape decides what it is.
            slots = (("A", cells[0], None),)

        for column, raw, declared in slots:
            if raw is None:
                continue
            if not isinstance(raw, str):
                workbook.violations.append(Violation(
                    "NON_TEXT_CELL", name, f"{column}{excel_row}", str(raw),
                    "cells must contain text; a number or a date is not a term"))
                continue
            text = normalise(raw)
            if not text:
                continue
            if text.casefold() in {TERM_HEADER.casefold(), KEYWORD_HEADER.casefold()}:
                workbook.violations.append(Violation(
                    "HEADER_IN_DATA", name, f"{column}{excel_row}", text,
                    "a header row appears in the middle of the data"))
                continue

            kind = declared
            if kind is None:  # legacy: infer, and record what was inferred
                kind = "term" if is_single_word(text) else "keyword"

            entry = Entry(text=text, row=excel_row, column=column)
            if kind == "term":
                _check_term(workbook, name, entry, text)
                _record_unique(workbook, name, entry, text, seen_terms,
                               "DUPLICATE_TERM", category.terms)
            else:
                _check_keyword(workbook, name, entry, text)
                _record_unique(workbook, name, entry, text, seen_keywords,
                               "DUPLICATE_KEYWORD", category.keywords)

    # A word that is also a phrase in the same sheet is a contradiction; a word
    # that merely *starts* a phrase is not.
    for term, term_entry in seen_terms.items():
        if term in seen_keywords:
            workbook.violations.append(Violation(
                "TERM_ALSO_KEYWORD", name, term_entry.cell, term_entry.text,
                f"the same text is also listed as a keyword "
                f"({seen_keywords[term].cell}); keep one"))

    if not category.terms and not category.keywords:
        workbook.violations.append(Violation(
            "SHEET_EMPTY", name, "", "", "the worksheet has no terms or keywords"))
    return category


def _check_term(workbook: Workbook, sheet: str, entry: Entry, text: str) -> None:
    if not is_single_word(text):
        workbook.violations.append(Violation(
            "TERM_HAS_WHITESPACE", sheet, entry.cell, text,
            f"a category term must be a single word ({word_count(text)} words "
            f"found); put a phrase in the {KEYWORD_HEADER} column"))
    if len(text) > MAX_TERM_CHARS:
        workbook.violations.append(Violation(
            "TERM_TOO_LONG", sheet, entry.cell, text,
            f"{len(text)} characters, the limit is {MAX_TERM_CHARS}"))


def _check_keyword(workbook: Workbook, sheet: str, entry: Entry, text: str) -> None:
    if not is_keyword(text):
        workbook.violations.append(Violation(
            "KEYWORD_SINGLE_WORD", sheet, entry.cell, text,
            f"a keyword must be two or more words; single words go in the "
            f"{TERM_HEADER} column"))
    if len(text) > MAX_KEYWORD_CHARS:
        workbook.violations.append(Violation(
            "KEYWORD_TOO_LONG", sheet, entry.cell, text,
            f"{len(text)} characters, the limit is {MAX_KEYWORD_CHARS}"))


def _record_unique(workbook: Workbook, sheet: str, entry: Entry, text: str,
                   seen: Dict[str, Entry], code: str, target: List[Entry]) -> None:
    key = text.casefold()
    if key in seen:
        workbook.violations.append(Violation(
            code, sheet, entry.cell, text,
            f"already listed at {seen[key].cell}"))
        return
    seen[key] = entry
    target.append(entry)


def _read_owners(sheet, workbook: Workbook) -> Dict[str, str]:
    """Read ``_Keyword Owners``: ``Phrase | Category``."""
    owners: Dict[str, str] = {}
    for index, row in enumerate(sheet.iter_rows(values_only=True)):
        cells = list(row) + [None, None]
        phrase, owner = normalise(cells[0]), normalise(cells[1])
        if not phrase or not owner:
            continue
        if index == 0 and phrase.casefold().startswith(("phrase", "keyword")):
            continue  # header
        key = phrase.casefold()
        if key in owners and owners[key] != owner:
            workbook.violations.append(Violation(
                "OWNER_CONFLICT", OWNERS_SHEET, f"A{index + 1}", phrase,
                f"listed twice, for {owners[key]!r} and {owner!r}"))
            continue
        owners[key] = owner
    return owners


def read(path: str, *, validate: bool = True,
         renames: Optional[Dict[str, str]] = None) -> Workbook:
    """Read and (by default) validate a workbook.

    ``renames`` declares that a worksheet was renamed (``{old: new}``). It is
    applied to the ``_Keyword Owners`` sheet as it is read, because the owner
    table names categories and a rename would otherwise leave entries pointing
    at a worksheet that no longer exists. The declaration is the operator's
    statement of intent, so the derived sheet follows it rather than blocking
    the sync.
    """
    import openpyxl

    book = openpyxl.load_workbook(path, read_only=True, data_only=True)
    workbook = Workbook(path=path)
    mapping = {normalise(old).casefold(): normalise(new)
               for old, new in (renames or {}).items()}
    try:
        for sheet in book.worksheets:
            name = normalise(sheet.title)
            if name.casefold() == OWNERS_SHEET.casefold():
                workbook.owners = _read_owners(sheet, workbook)
                continue
            if is_ignored_sheet(name):
                continue
            category = _read_category(sheet, workbook)
            if category is not None:
                workbook.categories.append(category)
    finally:
        book.close()

    if mapping and workbook.owners:
        workbook.owners = {
            phrase: mapping.get(normalise(owner).casefold(), owner)
            for phrase, owner in workbook.owners.items()
        }

    if validate:
        validate_structure(workbook)
    return workbook


def validate_structure(workbook: Workbook) -> None:
    """Sheet-level rules, and the keyword-ownership decisions.

    Split out from :func:`_read_category` so it can be re-run on a workbook the
    caller assembled in memory (the tests and the workbook writer both do).
    """
    workbook.violations = [v for v in workbook.violations
                           if v.code not in {"SHEET_NAME", "SHEET_EMPTY_SET",
                                             "KEYWORD_SHARED", "OWNER_UNKNOWN"}]

    seen_names: Dict[str, str] = {}
    for category in workbook.categories:
        name = category.name
        if not name:
            workbook.violations.append(Violation(
                "SHEET_NAME", name, "", "",
                "a worksheet name is required: it is the category name"))
            continue
        if name != normalise(name):
            workbook.violations.append(Violation(
                "SHEET_NAME", name, "", name,
                "the worksheet name has leading or trailing spaces"))
        if len(name) > MAX_SHEET_NAME_CHARS:
            workbook.violations.append(Violation(
                "SHEET_NAME", name, "", name,
                f"longer than Excel's {MAX_SHEET_NAME_CHARS}-character limit"))
        if name.startswith(IGNORED_PREFIX):
            workbook.violations.append(Violation(
                "SHEET_NAME", name, "", name,
                f"names starting with {IGNORED_PREFIX!r} are not categories"))
        if not is_single_word(name) and " " not in name:
            pass  # a category name may itself be a phrase; that is allowed
        key = name.casefold()
        if key in seen_names:
            workbook.violations.append(Violation(
                "SHEET_NAME", name, "", name,
                f"two worksheets claim the same category name "
                f"(the other is {seen_names[key]!r})"))
        else:
            seen_names[key] = name

    if not workbook.categories:
        workbook.violations.append(Violation(
            "SHEET_EMPTY_SET", "", "", "",
            "the workbook has no category worksheets"))

    # Keyword ownership, for phrases the schema can only store once.
    shared = workbook.shared_keywords()
    by_name = {c.name.casefold(): c for c in workbook.categories}
    used_owners = set()
    for phrase_key in sorted(shared):
        listed_in = shared[phrase_key]
        owner = workbook.owner_of(phrase_key)
        if owner is None:  # cannot happen for a shared phrase, but stay explicit
            continue
        used_owners.add(phrase_key)
        if owner.casefold() not in by_name:
            workbook.violations.append(Violation(
                "OWNER_UNKNOWN", OWNERS_SHEET, "", phrase_key,
                f"the owning category {owner!r} is not a worksheet"))
            continue
        others = [name for name in listed_in if name.casefold() != owner.casefold()]
        workbook.violations.append(Violation(
            "KEYWORD_SHARED", owner, "", phrase_key,
            f"listed in {len(listed_in)} worksheets ({', '.join(sorted(listed_in))});"
            f" the schema stores a keyword once, so it will belong to {owner!r}"
            f" and not to {', '.join(sorted(others))}",
            severity=_SEVERITY["decision"]))

    for phrase_key, owner in workbook.owners.items():
        if phrase_key not in shared:
            workbook.violations.append(Violation(
                "OWNER_UNKNOWN", OWNERS_SHEET, "", phrase_key,
                f"names {owner!r}, but no worksheet lists that phrase twice"))
        if owner.casefold() not in by_name:
            workbook.violations.append(Violation(
                "OWNER_UNKNOWN", OWNERS_SHEET, "", phrase_key,
                f"owner {owner!r} is not a worksheet; if the sheet was renamed, "
                f"pass --rename 'OLD=NEW' so the owner table follows it"))


# ---------------------------------------------------------------------------
# desired state, for the sync tool
# ---------------------------------------------------------------------------
@dataclass
class DesiredState:
    """What the database should contain, derived only from the workbook."""

    #: category name -> (terms, keywords) in workbook order
    categories: "collections.OrderedDict[str, Tuple[List[str], List[str]]]"
    #: phrase (casefolded) -> owning category, for the phrases actually stored
    keyword_owner: Dict[str, str]
    #: phrases that appear in more than one worksheet, and their owner
    shared: Dict[str, List[str]]

    def all_terms(self) -> List[str]:
        seen: Dict[str, str] = {}
        for terms, _keywords in self.categories.values():
            for term in terms:
                seen.setdefault(term.casefold(), term)
        return list(seen.values())

    def keywords_for(self, name: str) -> List[str]:
        terms, keywords = self.categories[name]
        return keywords

    def keyword_text(self, key: str, owner: Optional[str] = None) -> str:
        """The canonical spelling of a phrase, from the workbook that lists it."""
        names = [owner] if owner else list(self.categories)
        for name in names:
            if name not in self.categories:
                continue
            for text in self.categories[name][1]:
                if text.casefold() == key.casefold():
                    return text
        return key


def desired_state(workbook: Workbook) -> DesiredState:
    """Turn a validated workbook into the state the database should hold.

    Every phrase is assigned to exactly one category (see
    :meth:`Workbook.owner_of`); the others are recorded in ``shared`` so the
    sync can report what the schema cannot store.
    """
    categories: "collections.OrderedDict[str, Tuple[List[str], List[str]]]" = \
        collections.OrderedDict()
    for category in workbook.categories:
        categories[category.name] = (category.term_texts, category.keyword_texts)

    shared = workbook.shared_keywords()
    owner: Dict[str, str] = {}
    for name, (_terms, keywords) in categories.items():
        for phrase in keywords:
            key = phrase.casefold()
            if key in owner:
                continue
            if key in shared:
                owner[key] = workbook.owner_of(phrase) or name
            else:
                owner[key] = name
    return DesiredState(categories=categories, keyword_owner=owner, shared=shared)


# ---------------------------------------------------------------------------
# writing the workbook (used by the conversion and by --write-workbook)
# ---------------------------------------------------------------------------
def write(path: str, workbook: Workbook, *, index: bool = True) -> Dict[str, int]:
    """Write the workbook in the two-column layout.

    Rewriting the operator's file from the parsed content instead of patching it
    in place is deliberate: it makes the tool the only writer of the layout, so
    the header, the column order and the generated index cannot drift.
    """
    import openpyxl

    book = openpyxl.Workbook()
    book.remove(book.active)

    readme = book.create_sheet(README_SHEET)
    _write_readme(readme)

    counts = {"categories": 0, "terms": 0, "keywords": 0}
    for category in workbook.categories:
        sheet = book.create_sheet(category.name[:MAX_SHEET_NAME_CHARS])
        sheet.cell(row=1, column=1, value=TERM_HEADER)
        sheet.cell(row=1, column=2, value=KEYWORD_HEADER)
        for offset, text in enumerate(category.term_texts):
            sheet.cell(row=2 + offset, column=1, value=text)
        for offset, text in enumerate(category.keyword_texts):
            sheet.cell(row=2 + offset, column=2, value=text)
        _width(sheet, 34, 60)
        sheet.freeze_panes = "A2"
        counts["categories"] += 1
        counts["terms"] += len(category.terms)
        counts["keywords"] += len(category.keywords)

    shared = workbook.shared_keywords()
    if shared:
        owners = book.create_sheet(OWNERS_SHEET)
        owners.cell(row=1, column=1, value="Phrase")
        owners.cell(row=1, column=2, value="Category that owns it")
        owners.cell(row=1, column=3, value="Also listed in")
        for row, phrase_key in enumerate(sorted(shared), start=2):
            owner = workbook.owner_of(phrase_key) or ""
            others = [n for n in shared[phrase_key]
                      if n.casefold() != owner.casefold()]
            owners.cell(row=row, column=1, value=phrase_key)
            owners.cell(row=row, column=2, value=owner)
            owners.cell(row=row, column=3, value=", ".join(sorted(others)))
        _width(owners, 46, 34, 60)
        owners.freeze_panes = "A2"

    if index:
        index_sheet = book.create_sheet(INDEX_SHEET)
        _write_index(index_sheet, workbook)

    book.save(path)
    return counts


def _width(sheet, *widths: int) -> None:
    from openpyxl.utils import get_column_letter

    for number, width in enumerate(widths, start=1):
        sheet.column_dimensions[get_column_letter(number)].width = width


