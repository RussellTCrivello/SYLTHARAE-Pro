        (f"Column B, {KEYWORD_HEADER}: two or more words - a phrase or an expression.", False),
        ("", False),
        ("Rules", True),
        ("1. Worksheet name = category name. Renaming a sheet renames the category.", False),
        ("2. A term is exactly one word. 'Load balancing' belongs in the Keyword column.", False),
        ("3. A keyword is two or more words. 'Server' belongs in the Term column.", False),
        ("4. No duplicates within a worksheet, and one text cannot be both.", False),
        ("", False),
        ("How the database follows this file", True),
        ("Run:  python -m tools.i18n.sync_taxonomy --check     (validate only)", False),
        ("      python -m tools.i18n.sync_taxonomy --dry-run   (show the difference)", False),
        ("      python -m tools.i18n.sync_taxonomy --apply     (write it)", False),
